export function getProvinceNames() {
  return NEPAL_PROVINCES.map((p) => p.name);
}

export function getDistrictsByProvince(provinceName) {
  if (!provinceName) {
    return NEPAL_PROVINCES.flatMap((p) => p.districts.map((d) => d.name));
  }
  const province = NEPAL_PROVINCES.find((p) => p.name === provinceName);
  return province ? province.districts.map((d) => d.name) : [];
}

export function getMunicipalitiesByDistrict(provinceName, districtName) {
  if (!districtName) return [];
  const provincesToSearch = provinceName
    ? NEPAL_PROVINCES.filter((p) => p.name === provinceName)
    : NEPAL_PROVINCES;

  for (const prov of provincesToSearch) {
    const dist = prov.districts.find((d) => d.name === districtName);
    if (dist) return dist.municipalities;
  }
  return [];
}

export function findDistrictCoordinates(districtName) {
  for (const prov of NEPAL_PROVINCES) {
    const dist = prov.districts.find((d) => d.name === districtName);
    if (dist) return { ...dist.svgCoord, province: prov.name };
  }
  return { x: 518, y: 202, province: 'Bagmati Province' };
}
